/**
 * MindMate — Image Generation Service
 *
 * Dedicated service for handling explicit image generation requests.
 * Stays strictly decoupled from local Ollama text inference (gemma4:e2b-it-qat),
 * ensuring the local text model is never mistakenly treated as an image generation engine.
 *
 * Requirements:
 * - Explicit image-generation requests route to this service, NOT Ollama text generation.
 * - Clearly marks generated images as synthetic / AI-generated.
 * - Never fabricates fake image URLs or presents synthetic images as authentic historical photos.
 * - Discloses external provider dependencies and configuration transparently.
 */

export interface ImageGenerationOptions {
  style?: 'photorealistic' | 'diagram' | 'artistic' | 'minimalist';
  aspectRatio?: '1:1' | '16:9' | '4:3';
}

export interface GeneratedImageResult {
  success: boolean;
  isAIGenerated: true;
  label: string;
  provider: string;
  prompt: string;
  imageUrl?: string;
  caption?: string;
  error?: string;
}

const IMAGE_GENERATION_PATTERNS = [
  /^(?:please\s+)?generate\s+(?:an?\s+)?(?:image|picture|photo|illustration|drawing|artwork|art)\s+(?:of|showing|depicting)\s+(.+)/i,
  /^(?:please\s+)?create\s+(?:an?\s+)?(?:image|picture|photo|illustration|drawing|artwork)\s+(?:of|showing|depicting)\s+(.+)/i,
  /^(?:please\s+)?draw\s+(?:me\s+)?(?:an?\s+)?(?:picture|image|illustration|portrait)\s+(?:of\s+)?(.+)/i,
  /^(?:please\s+)?make\s+(?:an?\s+)?(?:image|picture|drawing)\s+(?:of|showing)\s+(.+)/i,
  /^(?:can\s+you\s+)?paint\s+(?:an?\s+)?(?:picture|image|scene)\s+(?:of\s+)?(.+)/i,
];

/**
 * Checks whether a user prompt is an explicit request to generate a new AI image
 */
export function isImageGenerationRequest(query: string): boolean {
  const q = query.trim();
  return IMAGE_GENERATION_PATTERNS.some((pattern) => pattern.test(q));
}

/**
 * Extracts the subject / prompt intended for image generation
 */
export function extractGenerationPrompt(query: string): string {
  const q = query.trim();
  for (const pattern of IMAGE_GENERATION_PATTERNS) {
    const match = q.match(pattern);
    if (match && match[1]) {
      return match[1].trim();
    }
  }
  return q;
}

/**
 * Generates an image using a configured image generation service, or returns a clear
 * configuration notice explaining that Ollama Gemma 4 is a local text LLM.
 */
export async function generateExplicitImage(
  userQuery: string,
  options?: ImageGenerationOptions
): Promise<GeneratedImageResult> {
  const targetPrompt = extractGenerationPrompt(userQuery);

  // Check if an external image generation endpoint is configured
  const configuredApiUrl =
    (typeof import.meta !== 'undefined' && import.meta.env?.VITE_IMAGE_GENERATION_API_URL) ||
    '';

  if (!configuredApiUrl) {
    return {
      success: false,
      isAIGenerated: true,
      label: 'AI Image Generation (Unconfigured)',
      provider: 'Image Generation Service',
      prompt: targetPrompt,
      error:
        'Local Gemma 4 (via Ollama) is a text-based language model and does not generate raster images. To enable generative images, configure an image-generation endpoint (e.g. VITE_IMAGE_GENERATION_API_URL) or view verified Wikimedia educational media.',
    };
  }

  try {
    const response = await fetch(configuredApiUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        prompt: targetPrompt,
        style: options?.style || 'photorealistic',
        aspectRatio: options?.aspectRatio || '1:1',
      }),
    });

    if (!response.ok) {
      throw new Error(`Image generation API responded with status ${response.status}`);
    }

    const data = await response.json();
    return {
      success: true,
      isAIGenerated: true,
      label: 'AI-Generated Image (Synthetic)',
      provider: data.provider || 'Configured Generative Model',
      prompt: targetPrompt,
      imageUrl: data.imageUrl || data.url,
      caption: `Synthetic AI illustration for "${targetPrompt}" (generated by ${data.provider || 'Image Model'}).`,
    };
  } catch (err: any) {
    return {
      success: false,
      isAIGenerated: true,
      label: 'AI Image Generation Error',
      provider: 'Configured Image Model',
      prompt: targetPrompt,
      error: err.message || 'Image generation service request failed.',
    };
  }
}
